package main

import (
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"errors"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"sort"
	"strings"
)

const outputName = "THIRD_PARTY_NOTICES"

type moduleInfo struct {
	Path    string
	Version string
	Dir     string
	Main    bool
	Replace *moduleInfo
}

type packageInfo struct {
	ImportPath string
	Standard   bool
	Module     *moduleInfo
}

type component struct {
	name    string
	version string
	spdx    string
	source  string
	text    []byte
}

func main() {
	root, err := os.Getwd()
	must(err)
	if _, err := os.Stat(filepath.Join(root, "go.mod")); err != nil {
		must(errors.New("run this generator from the repository root"))
	}

	packages := listPackages(root)
	components := moduleComponents(root, packages)
	components = append(components, assetComponents(root, packages)...)
	sort.Slice(components, func(i, j int) bool {
		if components[i].name != components[j].name {
			return components[i].name < components[j].name
		}
		return components[i].source < components[j].source
	})

	var out bytes.Buffer
	out.WriteString("Ryotunes third-party notices\n\n")
	out.WriteString("Generated by go run ./release/generate-third-party-notices.go. Do not edit.\n")
	out.WriteString("The component list comes from the packages linked into ./cmd/... with GOWORK=off.\n\n")
	out.WriteString("COMPONENTS\n==========\n\n")
	for _, c := range components {
		fmt.Fprintf(&out, "%s", c.name)
		if c.version != "" {
			fmt.Fprintf(&out, " %s", c.version)
		}
		fmt.Fprintf(&out, "\n  SPDX: %s\n  License file: %s\n\n", c.spdx, c.source)
	}

	out.WriteString("LICENSE TEXTS\n=============\n")
	for _, c := range components {
		fmt.Fprintf(&out, "\n--------------------------------------------------------------------------------\n%s", c.name)
		if c.version != "" {
			fmt.Fprintf(&out, " %s", c.version)
		}
		fmt.Fprintf(&out, "\nSPDX: %s\nSource: %s\n--------------------------------------------------------------------------------\n\n", c.spdx, c.source)
		out.Write(bytes.TrimSpace(c.text))
		out.WriteString("\n")
	}
	must(os.WriteFile(filepath.Join(root, outputName), out.Bytes(), 0o644))
}

func listPackages(root string) []packageInfo {
	cmd := exec.Command("go", "list", "-deps", "-json", "./cmd/...")
	cmd.Dir = root
	cmd.Env = append(os.Environ(), "GOWORK=off")
	stdout, err := cmd.StdoutPipe()
	must(err)
	var stderr bytes.Buffer
	cmd.Stderr = &stderr
	must(cmd.Start())

	decoder := json.NewDecoder(stdout)
	var packages []packageInfo
	for decoder.More() {
		var p packageInfo
		must(decoder.Decode(&p))
		packages = append(packages, p)
	}
	if err := cmd.Wait(); err != nil {
		must(fmt.Errorf("go list: %w: %s", err, strings.TrimSpace(stderr.String())))
	}
	return packages
}

func moduleComponents(root string, packages []packageInfo) []component {
	modules := make(map[string]moduleInfo)
	for _, p := range packages {
		if p.Standard || p.Module == nil || p.Module.Main {
			continue
		}
		module := *p.Module
		key := module.Path + "@" + module.Version
		modules[key] = module
	}

	keys := make([]string, 0, len(modules))
	for key := range modules {
		keys = append(keys, key)
	}
	sort.Strings(keys)

	components := make([]component, 0, len(keys)+1)
	for _, key := range keys {
		module := modules[key]
		dir := module.Dir
		if module.Replace != nil && module.Replace.Dir != "" {
			dir = module.Replace.Dir
		}
		licensePath, err := firstLicense(dir)
		if err != nil && module.Path == "github.com/xlab/vorbis-go" {
			licensePath = filepath.Join(root, "release", "notices", "xlab-vorbis-go.LICENSE")
			err = nil
		}
		must(err)
		text := mustRead(licensePath)
		components = append(components, component{
			name:    module.Path,
			version: module.Version,
			spdx:    identifyLicense(text),
			source:  noticePath(root, module.Path, licensePath),
			text:    text,
		})
	}

	licensePath := filepath.Join(root, "release", "notices", "go.LICENSE")
	licenseSource := "release/notices/go.LICENSE"
	text := mustRead(licensePath)
	components = append(components, component{
		name:   "Go standard library and runtime",
		spdx:   identifyLicense(text),
		source: licenseSource,
		text:   text,
	})
	return components
}

func assetComponents(root string, packages []packageInfo) []component {
	fontPath := filepath.Join(root, "internal", "client", "ui", "look", "fonts", "OFL.txt")
	fontText := mustRead(fontPath)
	components := []component{{
		name:   "Space Grotesk and Space Mono fonts",
		spdx:   "OFL-1.1",
		source: "internal/client/ui/look/fonts/OFL.txt",
		text:   fontText,
	}}

	for _, p := range packages {
		if p.ImportPath != "golang.org/x/exp/shiny/materialdesign/icons" || p.Module == nil {
			continue
		}
		dir := p.Module.Dir
		if p.Module.Replace != nil && p.Module.Replace.Dir != "" {
			dir = p.Module.Replace.Dir
		}
		licensePath := filepath.Join(dir, "materialdesign", "icons", "LICENSE")
		text := mustRead(licensePath)
		components = append(components, component{
			name:    "Material Design icons",
			version: p.Module.Version,
			spdx:    identifyLicense(text),
			source:  p.Module.Path + "/materialdesign/icons/LICENSE",
			text:    text,
		})
		break
	}
	return components
}

func firstLicense(dir string) (string, error) {
	for _, name := range []string{"LICENSE", "LICENSE.txt", "LICENSE.md", "COPYING", "COPYING.txt"} {
		path := filepath.Join(dir, name)
		if info, err := os.Stat(path); err == nil && !info.IsDir() {
			return path, nil
		}
	}
	return "", fmt.Errorf("no license file in %s", dir)
}

func identifyLicense(text []byte) string {
	s := string(text)
	upper := strings.Join(strings.Fields(strings.ToUpper(s)), " ")
	for _, expression := range []string{"Unlicense OR MIT", "Unlicense OR BSD-3-Clause"} {
		if strings.Contains(s, "SPDX-License-Identifier: "+expression) {
			return expression
		}
	}
	switch {
	case strings.Contains(upper, "SIL OPEN FONT LICENSE VERSION 1.1") || strings.Contains(upper, "SIL OPEN FONT LICENSE, VERSION 1.1"):
		return "OFL-1.1"
	case strings.Contains(upper, "GNU GENERAL PUBLIC LICENSE") && strings.Contains(upper, "VERSION 3, 29 JUNE 2007"):
		return "GPL-3.0-only"
	case strings.Contains(upper, "APACHE LICENSE") && strings.Contains(upper, "VERSION 2.0"):
		return "Apache-2.0"
	case strings.Contains(upper, "PERMISSION TO USE, COPY, MODIFY, AND DISTRIBUTE THIS SOFTWARE FOR ANY PURPOSE WITH OR WITHOUT FEE"):
		return "ISC"
	case strings.Contains(upper, "PERMISSION IS HEREBY GRANTED, FREE OF CHARGE"):
		return "MIT"
	case strings.Contains(upper, "REDISTRIBUTION AND USE IN SOURCE AND BINARY FORMS") && strings.Contains(upper, "NEITHER THE NAME"):
		return "BSD-3-Clause"
	case strings.Contains(upper, "REDISTRIBUTION AND USE IN SOURCE AND BINARY FORMS"):
		return "BSD-2-Clause"
	default:
		hash := sha256.Sum256(text)
		must(fmt.Errorf("unrecognized license text sha256:%s", hex.EncodeToString(hash[:])))
		return ""
	}
}

func noticePath(root, modulePath, path string) string {
	if relative, err := filepath.Rel(root, path); err == nil && !strings.HasPrefix(relative, "..") {
		return filepath.ToSlash(relative)
	}
	return modulePath + "/" + filepath.Base(path)
}

func mustRead(path string) []byte {
	text, err := os.ReadFile(path)
	must(err)
	return text
}

func must(err error) {
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}
